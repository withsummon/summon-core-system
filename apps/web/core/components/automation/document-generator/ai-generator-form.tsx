import React, { useId, useState } from "react";
import { Sparkles, Loader2 } from "lucide-react";
import { FormatPicker, MenuSelect, SelectChevron, StepHeader } from "./ai-generator-form-fields";
import { AVAILABLE_CONTEXTS, TOP_TEMPLATES } from "./mock-data";
import { TypeIcon } from "./type-icon";
import type { TDetailLevel, TDocumentFormat, TDocumentTone, TDocumentType, IGeneratedDocument } from "./types";

interface IAIGeneratorFormProps {
  selectedTemplate: TDocumentType;
  onTemplateChange: (tpl: TDocumentType) => void;
  onDocumentGenerated: (doc: IGeneratedDocument) => void;
}

const TONES: TDocumentTone[] = ["Professional", "Formal", "Technical", "Executive", "Casual"];
const DETAIL_LEVELS: TDetailLevel[] = ["Concise", "Standard", "Comprehensive", "In-depth"];
const TEMPLATE_NAMES = TOP_TEMPLATES.map((tpl) => tpl.name);
const TEMPLATE_BY_NAME = new Map(TOP_TEMPLATES.map((tpl) => [tpl.name, tpl]));

type TOpenMenu = "template" | "context" | "tone" | "detail" | null;

export const AIGeneratorForm: React.FC<IAIGeneratorFormProps> = ({
  selectedTemplate,
  onTemplateChange,
  onDocumentGenerated,
}) => {
  const fieldId = useId();
  const [context, setContext] = useState<string>(AVAILABLE_CONTEXTS[0]);
  const [additionalContext, setAdditionalContext] = useState<string>("");
  const [format, setFormat] = useState<TDocumentFormat>("DOCX");
  const [tone, setTone] = useState<TDocumentTone>("Professional");
  const [detailLevel, setDetailLevel] = useState<TDetailLevel>("Comprehensive");
  // only one option menu is open at a time
  const [openMenu, setOpenMenu] = useState<TOpenMenu>(null);

  const [isGenerating, setIsGenerating] = useState(false);

  const toggleMenu = (menu: Exclude<TOpenMenu, null>) => setOpenMenu((current) => (current === menu ? null : menu));

  const handleGenerate = () => {
    if (isGenerating) return;
    setIsGenerating(true);

    const newDoc: IGeneratedDocument = {
      id: `doc-${Date.now()}`,
      title: `${selectedTemplate} - ${context}`,
      description: additionalContext.trim()
        ? additionalContext.slice(0, 50) + (additionalContext.length > 50 ? "…" : "")
        : `AI Generated ${selectedTemplate.toLowerCase()} for ${context}`,
      type: selectedTemplate,
      context,
      createdBy: {
        name: "You (AI Assisted)",
        initials: "ME",
      },
      createdAt: "Just now",
      status: "Completed",
      format,
      content: `# ${selectedTemplate} - ${context}\n\n**Generated:** Just now\n**Tone:** ${tone} | **Detail Level:** ${detailLevel}\n**Format:** ${format}\n\n## Overview\nThis document was generated by AI using project context and workspace knowledge base.\n\n### Specifications & Details\n- **Project Scope:** ${context}\n${additionalContext ? `- **Additional Directives:** ${additionalContext}\n` : ""}- **Output Profile:** ${tone} tone with ${detailLevel.toLowerCase()} detail level.`,
    };

    setTimeout(() => {
      setIsGenerating(false);
      onDocumentGenerated(newDoc);
    }, 1200);
  };

  return (
    <div className="flex flex-col rounded-xl border border-subtle bg-surface-1 p-5 shadow-xs">
      {/* Title */}
      <div className="mb-5">
        <h2 className="text-base font-semibold text-primary">AI Document Generator</h2>
        <p className="mt-0.5 text-xs text-secondary">Generate documents with AI in minutes</p>
      </div>

      <div className="space-y-4">
        {/* STEP 1: Select Template */}
        <div>
          <StepHeader step={1} title="Select Template" htmlFor={`${fieldId}-template`} />
          <MenuSelect
            id={`${fieldId}-template`}
            isOpen={openMenu === "template"}
            onToggle={() => toggleMenu("template")}
            value={selectedTemplate}
            options={TEMPLATE_NAMES}
            onSelect={(name) => {
              onTemplateChange(name);
              const defaultFormat = TEMPLATE_BY_NAME.get(name)?.defaultFormat;
              if (defaultFormat) setFormat(defaultFormat);
              setOpenMenu(null);
            }}
            buttonClassName="py-2 font-medium"
            buttonContent={
              <>
                <div className="flex items-center gap-2">
                  <TypeIcon type={selectedTemplate} size={15} />
                  <span>{selectedTemplate}</span>
                </div>
                <SelectChevron size={14} />
              </>
            }
            optionClassName="py-2"
            checkSize={13}
            renderOption={(name) => (
              <div className="flex items-center gap-2">
                <TypeIcon type={name} size={14} />
                <span>{TEMPLATE_BY_NAME.get(name)?.title}</span>
              </div>
            )}
          />
        </div>

        {/* STEP 2: Select Context */}
        <div>
          <StepHeader step={2} title="Select Context" htmlFor={`${fieldId}-context`} />
          <MenuSelect
            id={`${fieldId}-context`}
            isOpen={openMenu === "context"}
            onToggle={() => toggleMenu("context")}
            value={context}
            options={AVAILABLE_CONTEXTS}
            onSelect={(item) => {
              setContext(item);
              setOpenMenu(null);
            }}
            buttonClassName="py-2 font-medium"
            buttonContent={
              <>
                <div className="flex items-center gap-2 truncate">
                  <span className="truncate">{context}</span>
                  <span className="font-normal rounded bg-layer-2 px-1.5 py-0.5 text-[10px] text-secondary">
                    Project
                  </span>
                </div>
                <SelectChevron size={14} className="ml-2 shrink-0" />
              </>
            }
            menuClassName="max-h-48 overflow-y-auto"
            optionClassName="py-2"
            checkSize={13}
            checkClassName="ml-2 shrink-0"
            renderOption={(item) => <span className="truncate">{item}</span>}
          />
        </div>

        {/* STEP 3: Additional Context (Optional) */}
        <div>
          <StepHeader step={3} title="Additional Context (Optional)" htmlFor={`${fieldId}-additional`} />
          <div className="relative">
            <textarea
              id={`${fieldId}-additional`}
              rows={3}
              maxLength={1000}
              value={additionalContext}
              onChange={(e) => setAdditionalContext(e.target.value)}
              placeholder="Add more details about the project, scope, or enter specific requirements…"
              className="w-full resize-none rounded-lg border border-subtle bg-surface-2 p-2.5 text-xs text-primary transition-colors outline-none placeholder:text-placeholder focus-visible:border-accent-strong"
            />
            <div className="absolute right-2 bottom-2 text-[10px] text-placeholder">
              {additionalContext.length}/1000
            </div>
          </div>
        </div>

        {/* STEP 4: Output Preferences */}
        <div>
          <StepHeader step={4} title="Output Preferences" className="mb-2" />

          <div className="space-y-3 pl-6">
            <FormatPicker value={format} onChange={setFormat} />

            {/* Tone Selector */}
            <div>
              <span className="mb-1 block text-[11px] font-medium text-secondary">Tone</span>
              <MenuSelect
                isOpen={openMenu === "tone"}
                onToggle={() => toggleMenu("tone")}
                value={tone}
                options={TONES}
                onSelect={(value) => {
                  setTone(value);
                  setOpenMenu(null);
                }}
                buttonClassName="py-1.5"
                buttonContent={
                  <>
                    <span>{tone}</span>
                    <SelectChevron />
                  </>
                }
              />
            </div>

            {/* Detail Level */}
            <div>
              <span className="mb-1 block text-[11px] font-medium text-secondary">Detail Level</span>
              <MenuSelect
                isOpen={openMenu === "detail"}
                onToggle={() => toggleMenu("detail")}
                value={detailLevel}
                options={DETAIL_LEVELS}
                onSelect={(value) => {
                  setDetailLevel(value);
                  setOpenMenu(null);
                }}
                buttonClassName="py-1.5"
                buttonContent={
                  <>
                    <span>{detailLevel}</span>
                    <SelectChevron />
                  </>
                }
              />
            </div>
          </div>
        </div>

        {/* Generate Button */}
        <div className="pt-2">
          <button
            type="button"
            disabled={isGenerating}
            onClick={handleGenerate}
            className="flex w-full items-center justify-center gap-2 rounded-lg bg-accent-primary py-2.5 text-xs font-semibold text-on-color shadow-sm transition-[background-color,scale,opacity] hover:bg-accent-primary-hover active:scale-[0.99] disabled:opacity-75"
          >
            {isGenerating ? (
              <>
                <Loader2 size={15} className="animate-spin" />
                <span>Generating Document…</span>
              </>
            ) : (
              <>
                <Sparkles size={15} />
                <span>Generate Document</span>
              </>
            )}
          </button>
          <p className="mt-2 text-center text-[11px] text-placeholder">
            AI will use project context and knowledge base
          </p>
        </div>
      </div>
    </div>
  );
};
